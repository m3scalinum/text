using System;
using System.Collections.Generic;
using System.Globalization;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace M3scalinum.Text.SharpTypst.Templates.Generator;

/// <summary>
/// Turns a <c>template.toml</c> manifest into a typed options record, so a template is filled from
/// a compile-time-checked type instead of a <c>Dictionary&lt;string, object?&gt;</c>.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class TypstTemplateGenerator : IIncrementalGenerator
{
    private const string AttributeName = "M3scalinum.Text.SharpTypst.Templates.TypstTemplateAttribute";
    private const string ManifestFileName = "template.toml";

    /// <inheritdoc />
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var manifests = context.AdditionalTextsProvider
            .Where(static file => file.Path.EndsWith(ManifestFileName, StringComparison.OrdinalIgnoreCase))
            .Select(static (file, token) => new ManifestSource(file.Path, file.GetText(token)?.ToString()))
            .Collect();

        var targets = context.SyntaxProvider
            .ForAttributeWithMetadataName(
                AttributeName,
                static (node, _) => node is TypeDeclarationSyntax,
                static (ctx, _) => TemplateTarget.From(ctx))
            .Where(static target => target is not null)
            .Select(static (target, _) => target!);

        context.RegisterSourceOutput(
            targets.Combine(manifests),
            static (spc, pair) => Execute(spc, pair.Left, pair.Right));
    }

    private static void Execute(
        SourceProductionContext context,
        TemplateTarget target,
        IReadOnlyList<ManifestSource> manifests)
    {
        if (!target.IsPartial)
        {
            context.ReportDiagnostic(Diagnostic.Create(Diagnostics.NotPartial, target.Location, target.TypeName));
            return;
        }

        if (target.HasPrimaryConstructor)
        {
            context.ReportDiagnostic(
                Diagnostic.Create(Diagnostics.HasPrimaryConstructor, target.Location, target.TypeName));
            return;
        }

        var manifest = Find(manifests, target.Path);
        if (manifest is null)
        {
            context.ReportDiagnostic(
                Diagnostic.Create(Diagnostics.ManifestNotFound, target.Location, target.Path));
            return;
        }

        IReadOnlyList<TemplateParameter> parsed;
        try
        {
            parsed = ManifestReader.ReadParameters(manifest.Text ?? string.Empty);
        }
        catch (FormatException exception)
        {
            context.ReportDiagnostic(
                Diagnostic.Create(Diagnostics.InvalidManifest, target.Location, manifest.Path, exception.Message));
            return;
        }

        var source = Emit(target, parsed, context);
        context.AddSource(target.TypeName + ".TypstTemplate.g.cs", SourceText.From(source, Encoding.UTF8));
    }

    private static ManifestSource? Find(IReadOnlyList<ManifestSource> manifests, string path)
    {
        var wanted = path.Replace('\\', '/').Trim('/');

        foreach (var manifest in manifests)
        {
            var file = manifest.Path.Replace('\\', '/');
            var directory = file.Substring(0, file.Length - ManifestFileName.Length).TrimEnd('/');

            if (directory.EndsWith("/" + wanted, StringComparison.OrdinalIgnoreCase)
                || directory.Equals(wanted, StringComparison.OrdinalIgnoreCase))
            {
                return manifest;
            }
        }

        return null;
    }

    private static string Emit(TemplateTarget target, IReadOnlyList<TemplateParameter> parameters, SourceProductionContext context)
    {
        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated/>");
        builder.AppendLine("#nullable enable");
        builder.AppendLine();

        if (!string.IsNullOrEmpty(target.Namespace))
        {
            builder.Append("namespace ").Append(target.Namespace).AppendLine(";");
            builder.AppendLine();
        }

        builder.Append("partial ").Append(target.Keyword).Append(' ').Append(target.TypeName)
            .AppendLine(" : global::M3scalinum.Text.SharpTypst.Templates.ITypstTemplateOptions");
        builder.AppendLine("{");

        foreach (var parameter in parameters)
        {
            var property = ToPascalCase(parameter.Name);
            var type = MapType(parameter.Type, parameter.ItemType, parameter.Name, target.Location, context);

            builder.Append("    /// <summary>Template parameter <c>").Append(EscapeXml(parameter.Name))
                .AppendLine("</c>.</summary>");
            builder.Append("    public ");
            if (parameter.Required)
            {
                builder.Append("required ");
            }

            builder.Append(type).Append(' ').Append(property).Append(" { get; init; }");

            if (!parameter.Required)
            {
                // An auto-property with an initializer needs the trailing semicolon; one without
                // does not, because the accessor list already ends with one.
                builder.Append(" = ").Append(RenderDefault(parameter)).Append(';');
            }

            builder.AppendLine();
            builder.AppendLine();
        }

        builder.AppendLine("    /// <inheritdoc />");
        builder.AppendLine("    public global::System.Collections.Generic.IReadOnlyDictionary<string, object?> ToParameters()");
        builder.AppendLine("        => new global::System.Collections.Generic.Dictionary<string, object?>(global::System.StringComparer.Ordinal)");
        builder.AppendLine("        {");

        foreach (var parameter in parameters)
        {
            builder.Append("            [\"").Append(parameter.Name).Append("\"] = ")
                .Append(ToPascalCase(parameter.Name)).AppendLine(",");
        }

        builder.AppendLine("        };");
        builder.AppendLine("}");

        return builder.ToString();
    }

    private static string MapType(
        string type,
        string? itemType,
        string parameterName,
        Location location,
        SourceProductionContext context)
    {
        switch (type)
        {
            case "string":
            case "asset":
                return "string";
            case "number":
                return "double";
            case "boolean":
                return "bool";
            case "date":
                return "global::System.DateOnly";
            case "object":
                return "global::System.Collections.Generic.IReadOnlyDictionary<string, object?>";
            case "array":
                var element = MapType(itemType ?? "string", null, parameterName, location, context);
                return "global::System.Collections.Generic.IReadOnlyList<" + element + ">";
            default:
                context.ReportDiagnostic(
                    Diagnostic.Create(Diagnostics.UnsupportedType, location, parameterName, type));
                return "object?";
        }
    }

    private static string RenderDefault(TemplateParameter parameter)
    {
        switch (parameter.Default)
        {
            case string text:
                return SymbolDisplay.FormatLiteral(text, quote: true);
            case bool flag:
                return flag ? "true" : "false";
            case long number:
                return number.ToString(CultureInfo.InvariantCulture);
            case double real:
                return real.ToString("R", CultureInfo.InvariantCulture);
            default:
                return "default!";
        }
    }

    private static string ToPascalCase(string name)
    {
        var builder = new StringBuilder(name.Length);
        var upper = true;

        foreach (var character in name)
        {
            if (character == '_' || character == '-' || character == ' ')
            {
                upper = true;
                continue;
            }

            builder.Append(upper ? char.ToUpperInvariant(character) : character);
            upper = false;
        }

        return builder.Length == 0 ? "Value" : builder.ToString();
    }

    private static string EscapeXml(string text)
        => text.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");

    /// <summary>One <c>template.toml</c> found in the compilation.</summary>
    private sealed class ManifestSource
    {
        public ManifestSource(string path, string? text)
        {
            Path = path;
            Text = text;
        }

        public string Path { get; }

        public string? Text { get; }
    }

    /// <summary>One type carrying <c>[TypstTemplate]</c>.</summary>
    private sealed class TemplateTarget
    {
        private TemplateTarget(
            string? @namespace,
            string typeName,
            string keyword,
            bool isPartial,
            bool hasPrimaryConstructor,
            string path,
            Location location)
        {
            Namespace = @namespace;
            TypeName = typeName;
            Keyword = keyword;
            IsPartial = isPartial;
            HasPrimaryConstructor = hasPrimaryConstructor;
            Path = path;
            Location = location;
        }

        public string? Namespace { get; }

        public string TypeName { get; }

        public string Keyword { get; }

        public bool IsPartial { get; }

        public bool HasPrimaryConstructor { get; }

        public string Path { get; }

        public Location Location { get; }

        public static TemplateTarget? From(GeneratorAttributeSyntaxContext context)
        {
            if (context.TargetSymbol is not INamedTypeSymbol symbol
                || context.TargetNode is not TypeDeclarationSyntax syntax
                || context.Attributes.Length == 0)
            {
                return null;
            }

            var path = context.Attributes[0].ConstructorArguments.Length > 0
                ? context.Attributes[0].ConstructorArguments[0].Value as string
                : null;

            if (string.IsNullOrEmpty(path))
            {
                return null;
            }

            var keyword = syntax switch
            {
                RecordDeclarationSyntax record
                    when record.ClassOrStructKeyword.IsKind(SyntaxKind.StructKeyword) => "record struct",
                RecordDeclarationSyntax => "record",
                StructDeclarationSyntax => "struct",
                _ => "class",
            };

            return new TemplateTarget(
                symbol.ContainingNamespace.IsGlobalNamespace ? null : symbol.ContainingNamespace.ToDisplayString(),
                symbol.Name,
                keyword,
                syntax.Modifiers.Any(SyntaxKind.PartialKeyword),
                syntax.ParameterList is not null,
                path!,
                syntax.Identifier.GetLocation());
        }
    }
}
